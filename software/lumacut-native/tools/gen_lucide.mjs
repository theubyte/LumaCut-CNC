// Generates app/src/LucideIcons.cpp from a lucide-react checkout (ISC licence). Icon names in QML are kebab-case.
//   node tools/gen_lucide.mjs <path to node_modules/lucide-react> Name1 Name2 ...
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const [root, ...names] = process.argv.slice(2);
const index = readFileSync(join(root, 'dist/esm/lucide-react.mjs'), 'utf8');
const kebab = (s) => s.replace(/([a-z])([A-Z0-9])/g, '$1-$2').replace(/([0-9])([A-Z])/g, '$1-$2').toLowerCase().replace('grid-3x-3', 'grid-3x3').replace('xcircle', 'x-circle');
let out = '// Generated by tools/gen_lucide.mjs. Icon outlines from Lucide (https://lucide.dev), ISC licence.\n#include "LucideIcons.h"\n\nconst char* lucideIconBody(const QString& name) {\n    static const QHash<QString, const char*> icons = {\n';
for (const name of [...new Set(names)].sort()) {
  const m = index.match(new RegExp(`default as ${name}(?:[ ,][^}]*)?\} from '\./icons/([^']+)'`)) ?? index.match(new RegExp(`\b${name}\b[^}]*\} from '\./icons/([^']+)'`));
  if (!m) { console.error('fehlt', name); continue; }
  const src = readFileSync(join(root, 'dist/esm/icons', m[1]), 'utf8');
  const node = eval('(' + src.match(/const __iconData = (\{[\s\S]*?\n\});/)[1] + ')').node;
  const body = node.map(([tag, a]) => `<${tag} ${Object.entries(a).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
  out += `        {QStringLiteral("${kebab(name)}"), R"svg(${body})svg"},\n`;
}
out += '    };\n    return icons.value(name, nullptr);\n}\n';
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../app/src/LucideIcons.cpp'), out);
